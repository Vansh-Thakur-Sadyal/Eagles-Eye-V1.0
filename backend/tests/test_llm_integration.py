def test_provider_switching_needs_no_code_change(stub_server):
    """Every supported provider builds a client from configuration alone."""
    for provider in ("openai_compatible", "ollama", "anthropic", "mistral"):
        client = LLMClient()
        client.provider = provider
        client.base_url = stub_server
        client.api_key = "k"
        client.model = "m"
        assert client.enabled is True, f"{provider} would not enable from config"
        assert client.info()["provider"] == provider
