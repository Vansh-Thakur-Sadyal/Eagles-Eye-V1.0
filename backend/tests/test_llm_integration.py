T0 = datetime(2026, 1, 15, 18, 42, 0, tzinfo=timezone.utc)


# ------------------------------------------------------------- stub server
class _Handler(BaseHTTPRequestHandler):
    """Minimal OpenAI-compatible /v1/chat/completions."""

    mode = "ok"                      # ok | error | garbage
    last_request: Optional[Dict[str, Any]] = None

    def log_message(self, *args):    # keep pytest output clean
        pass

    def do_POST(self):
        length = int(self.headers.get("Content-Length", 0))
        body = json.loads(self.rfile.read(length) or b"{}")
        type(self).last_request = body

        if type(self).mode == "error":
            self.send_response(500)
            self.end_headers()
            self.wfile.write(b'{"error":"upstream exploded"}')
            return

        if type(self).mode == "garbage":
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.end_headers()
            self.wfile.write(b"this is not json at all")
            return

        prompt = json.dumps(body.get("messages", []))
        reply = (
            "STUBBED NARRATION: a suitcase has been stationary near Gate 4 for 78 "
            "seconds with no associated subject nearby. Crowd density is moderate. "
            "Recommend operator review."
        )
        if "json" in prompt.lower() and "report" in prompt.lower():
            reply = "# Stub report\n\n- generated by the stub provider\n"

        payload = {
            "id": "chatcmpl-stub",
            "object": "chat.completion",
            "choices": [{"index": 0, "message": {"role": "assistant", "content": reply},
                         "finish_reason": "stop"}],
            "usage": {"prompt_tokens": 10, "completion_tokens": 20, "total_tokens": 30},
        }
        raw = json.dumps(payload).encode()
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)


@pytest.fixture(scope="module")
def stub_server():
    server = HTTPServer(("127.0.0.1", 0), _Handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    host, port = server.server_address
    yield f"http://{host}:{port}/v1"
    server.shutdown()
    server.server_close()


