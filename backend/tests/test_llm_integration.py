# --------------------------------------------------------------- the client
def test_disabled_provider_reports_itself_honestly():
    client = LLMClient()
    client.provider = "none"
    assert client.enabled is False
    assert client.info()["enabled"] is False
    with pytest.raises(LLMUnavailable):
        client.complete([{"role": "user", "content": "hello"}])


def test_health_check_round_trips(stub_llm):
    health = stub_llm.health()
    assert health["ok"] is True
    assert health["provider"] == "openai_compatible"
    assert health["model"] == "stub-model"


def test_completion_sends_a_well_formed_request(stub_llm):
    reply = stub_llm.complete(
        [{"role": "system", "content": "be terse"}, {"role": "user", "content": "status?"}],
        temperature=0.1, max_tokens=64,
    )
    assert "STUBBED NARRATION" in reply

    sent = _Handler.last_request
    assert sent["model"] == "stub-model"
    assert sent["temperature"] == 0.1
    assert sent["max_tokens"] == 64
    assert [m["role"] for m in sent["messages"]] == ["system", "user"]


def test_upstream_failure_raises_llm_unavailable(stub_llm):
    _Handler.mode = "error"
    try:
        with pytest.raises(LLMUnavailable):
            stub_llm.complete([{"role": "user", "content": "hi"}])
    finally:
        _Handler.mode = "ok"


def test_json_extraction_survives_prose_and_fences():
    assert extract_json('{"a": 1}') == {"a": 1}
    assert extract_json('```json\n{"a": 2}\n```') == {"a": 2}
    assert extract_json('Sure! Here you go:\n{"a": 3}\nHope that helps.') == {"a": 3}
    assert extract_json("[1, 2, 3]") == [1, 2, 3]
    with pytest.raises(ValueError):
        extract_json("no json here at all")


# ------------------------------------------------------------ the commander
def _assessment():
    findings = [Finding("unattended_object", 0.92, "high", started_at=T0, ended_at=T0,
                        explanation="A suitcase has been stationary for 78s.")]
    return findings, ThreatAssessor().assess(findings, load_policy(), now=T0)


def test_narration_uses_the_llm_when_one_is_configured(stub_llm):
    findings, assessment = _assessment()
    out = IncidentCommander().compose(
        findings=findings, assessment=assessment,
        camera={"id": "CAM_1", "name": "Gate 4", "location": "Terminal A"}, now=T0,
    )
    assert out["narration_source"] == "llm:openai_compatible"
    assert "STUBBED NARRATION" in out["summary"]


def test_narration_falls_back_to_template_when_the_llm_breaks(stub_llm):
    """A dead provider must cost wording, never capability."""
    _Handler.mode = "error"
    try:
        findings, assessment = _assessment()
        commander = IncidentCommander()
        out = commander.compose(
            findings=findings, assessment=assessment,
            camera={"id": "CAM_1", "name": "Gate 4", "location": "Terminal A"}, now=T0,
        )
        assert out["narration_source"] == "template"
        assert out["summary"], "the fallback produced no summary at all"
        assert "stationary" in out["summary"].lower()
        # Everything else must still be present.
        assert out["recommended_actions"]
        assert out["timeline"]
        assert out["risk_factors"]
        assert commander.llm_failures == 1
    finally:
        _Handler.mode = "ok"


def test_llm_narration_still_carries_the_guardrails(stub_llm):
    """The system prompt must state the limits the platform enforces."""
    import app.agents.commander as commander_module

