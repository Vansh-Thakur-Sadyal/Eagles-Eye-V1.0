def test_forensic_answer_uses_the_llm(stub_llm, monkeypatch):
    from app.rag.forensic import ForensicSearch
    from app.rag.vectorstore import MemoryStore, incident_to_document

    store = MemoryStore()
    store.upsert([incident_to_document({
        "id": "INC_LLM001", "title": "Potentially unattended object",
        "summary": "A suitcase near Gate 4 has been stationary for 78 seconds.",
        "explanation": "Risk driven by unattended_object.",
        "behaviors": ["unattended_object"], "camera_id": "CAM_1",
        "camera_name": "Gate 4", "zone_id": "Z1", "site_id": "S1",
        "event_type": "unattended_object", "severity": "high", "risk_score": 78.0,
        "started_at": T0.isoformat(), "location": {"zone_name": "Gate 4"},
        "track_ids": ["T_104"],
    })])
    import app.rag.forensic as forensic_module

    monkeypatch.setattr(forensic_module, "get_store", lambda: store)

    result = ForensicSearch().answer("unattended suitcase near gate 4", now=T0)
    assert result["answer_source"] == "llm:openai_compatible"
    assert "STUBBED NARRATION" in result["answer"]
    # Grounding must survive: citations come from retrieval, not from the model.
    assert [c["incident_id"] for c in result["citations"]] == ["INC_LLM001"]


