"""LLM integration, verified against a stub provider.

Runs a real OpenAI-compatible HTTP server in-process and points Sentinel at it,
so the wiring is proven end to end without needing anybody's API key. When you
add real credentials, the only thing that changes is the base URL.

The fallback behaviour is tested just as hard as the success path: an
unreachable or broken provider must degrade the *wording* of a narration, never
the capability. A dead LLM is not allowed to mean "no incident summary".
"""
